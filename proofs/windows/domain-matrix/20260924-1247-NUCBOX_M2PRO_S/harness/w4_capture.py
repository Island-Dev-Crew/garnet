"""Garnet domain-matrix capture harness (NUC evidence seat): fresh Windows and WSL bundles.

One invocation (`all`) runs, in order, stopping at the first failed gate:
  clone     fresh Windows clone of the public repo, commit identity
  env       environment captures
  baseline  evidence-integrity gate and the readiness test BEFORE any new bundle
  windows   scripts/smoke_garnet_studio_domain_matrix.py on native Windows
  wsl       fresh clone on the WSL ext4 home, the same script there, then a
            byte-verified copy of the WSL bundle into the Windows clone
  verify    manifests, the integrity gate, the readiness test and its lane
  post      post-run state of both clones

Every step is a child process from an argv list (no shell on the Windows side),
stdin closed, stdout and stderr captured unedited into streams/. WSL steps run a
bash script file generated into harness/wsl/ (so no command line is re-quoted);
each script echoes its own exit status as its last stdout line. Every record
carries this file's sha256. The seat's folder is staged outside the clone; the
two domain-matrix bundles are written into the clone by the script that owns
them, as the task specifies.

Usage (Python 3.12, from native PowerShell):
    python w4_capture.py all --stamp YYYYMMDD-HHMM
    python w4_capture.py render --stamp YYYYMMDD-HHMM
"""

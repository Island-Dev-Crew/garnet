        "import re, sys\n"
        "def parse(p):\n"
        "    t = open(p, 'rb').read().decode('utf-8', 'replace')\n"
        "    bad = set(re.findall(r'^(?:FAIL|ERROR): (\\S+) ', t, re.M))\n"
        "    ran = re.findall(r'^Ran (\\d+) tests', t, re.M)\n"
        "    return bad, ran\n"
        f"b, rb = parse(r'{before}')\n"
        f"a, ra = parse(r'{after}')\n"
        f"target = {TARGET_TEST.split('.')[-1]!r}\n"
        "print('before: ran=' + ','.join(rb) + ' failing=' + ', '.join(sorted(b)))\n"

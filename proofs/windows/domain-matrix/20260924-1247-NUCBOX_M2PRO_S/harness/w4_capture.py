def census_row(path: Path, rel: str) -> dict:
    data = path.read_bytes()
    bom = "utf-8" if data.startswith(b"\xef\xbb\xbf") else "utf-16le" if data.startswith(b"\xff\xfe") else \
        "utf-16be" if data.startswith(b"\xfe\xff") else "none"
    try:
        data.decode("utf-8")
        utf8 = True
    except UnicodeDecodeError:
        utf8 = False
    crlf = data.count(b"\r\n")
    lf = data.count(b"\n") - crlf
    cr = data.count(b"\r") - crlf
    endings = ("empty" if not data else "no-newline" if not (crlf or lf or cr) else "CRLF" if crlf and not lf and not cr
               else "LF" if lf and not crlf and not cr else "MIXED")
    return dict(path=rel, bytes=len(data), sha256=hashlib.sha256(data).hexdigest(), utf8=utf8, bom=bom, endings=endings,
                lf=lf, crlf=crlf, cr=cr, nonascii=sum(1 for b in data if b > 127), nul=data.count(0),
                finalnl=data.endswith(b"\n"))


def section_doc(title: str, recs: list[dict], ctx: Ctx, preamble: str) -> bytes:
    out = bytearray(f"# {title}\n{preamble}".encode())
    for r in recs:
        out += b"\n" + b"=" * 78 + b"\n" + f"[{r['id']}] {r['title']}\n".encode()
        if r["script"]:
            out += f"$ ({r['script_lang']}{', ' + r['script_file'] if r['script_file'] else ''})\n  ".encode()
            out += r["script"].rstrip("\n").replace("\n", "\n  ").encode() + b"\n"
        else:
            out += f"$ {r['display']}\n".encode()
        out += (f"exit_code={r['exit_code']} expected={r['expect_exit']} timed_out={r['timed_out']} "
                f"started={r['started_utc']} duration_s={r['duration_s']} path={r['path_mode']}\n").encode()
        for st in r["streams"]:
            raw = (ctx.seat / st["file"]).read_bytes()
            out += f"--- {st['kind']} ({st['file']}, {st['bytes']} bytes, sha256 {st['sha256']})\n".encode() + raw
            if raw and not raw.endswith(b"\n"):
                out += b"\n[no trailing newline in the captured stream]\n"
            out += f"--- end {st['kind']}\n".encode()
    return bytes(out)


def cmd_render(ctx: Ctx) -> None:
    recs = [json.loads(l) for l in ctx.log.read_text(encoding="utf-8").splitlines() if l.strip()]
    run = json.loads(ctx.run_json.read_text(encoding="utf-8"))
    head = (ctx.seat / "streams" / "E11-head.stdout").read_text(encoding="ascii").strip()
    by: dict[str, list] = {}
    for r in recs:
        by.setdefault(r["section"], []).append(r)
    pre = (f"folder: proofs/windows/domain-matrix/{ctx.seat.name}/\n"
           f"bundles: {ctx.win_bundle_rel}/ and {ctx.wsl_bundle_rel}/ (each sealed by its own MANIFEST.sha256,\n"
           "  written by scripts/smoke_garnet_studio_domain_matrix.py)\n"
           f"host: {HOST} (%COMPUTERNAME%; `hostname` prints the DNS casing, see E01)\n"
           f"main: {head}\nstamp: {ctx.stamp} (UTC)\n"
           f"harness: harness/w4_capture.py, sha256 {run['harness_sha256']}; every step ran from this one invocation\n"
           f"  ({' '.join(Path(a).name if i == 0 else a for i, a in enumerate(run['argv']))}), "
           f"{run['started_utc']} to {run['ended_utc']}.\n"
           "python (Windows): every Windows python step ran with Python312 first on PATH except E08, which shows the\n"
           "  machine's default PATH (an unrelated 3.11.15 virtualenv).\n"
           f"wsl: steps X01-X05 and P02 run bash script files (harness/wsl/) inside WSL distro {DISTRO}; each script\n"
           "  prints `wsl_script_exit=<rc>` as its last stdout line, recorded next to wsl.exe's exit code.\n"
           "powershell: PowerShell steps run powershell.exe 5.1 with -EncodedCommand; with redirected output it writes\n"
           "  progress/error records to stderr as CLIXML. The raw streams are authoritative.\n"
           "captures: stdout and stderr are the raw child-process bytes, unedited; see encoding-census.txt.\n")
    docs = {"env.txt": ("Clone and environment captures", ["env"]),
            "baseline.txt": ("Before any new bundle: integrity gate, readiness lane, target test", ["baseline"]),
            "matrix-windows.txt": ("Domain matrix on native Windows", ["windows"]),
            "matrix-wsl.txt": ("Domain matrix in WSL, and the copy into the Windows clone", ["wsl"]),
            "verify.txt": ("After both bundles: manifests, integrity gate, readiness lane, tests, post-run state",
                           ["verify", "post"])}
    for name, (title, sections) in docs.items():
        (ctx.seat / name).write_bytes(section_doc(title, [r for sec in sections for r in by.get(sec, [])], ctx, pre))
    lines = [f"# Commands run for proofs/windows/domain-matrix/{ctx.seat.name}/", pre.rstrip("\n"),
             f"run: stopped_at={run['stopped_at']} unexpected_exits={run['unexpected_exits']}", ""]
    for r in recs:
        lines += ["=" * 78, f"[{r['id']}] {r['title']}   (phase {r['phase']})"]
        if r["script"]:
            lines.append(f"command ({r['script_lang']}{', file ' + r['script_file'] if r['script_file'] else ''}):")
            lines += ["    " + l for l in r["script"].rstrip("\n").split("\n")]
            argv_shown = r["argv"][:-1] + ["<base64 UTF-16LE of the script above>"] if r["script_lang"].startswith(
                "PowerShell") else r["argv"]
        else:
            lines.append(f"command: {r['display']}")
            argv_shown = r["argv"]
        lines += ["argv: " + json.dumps(argv_shown, ensure_ascii=False), f"resolved_exe: {r['resolved_exe']}",
                  f"cwd: {r['cwd']}   path: {r['path_mode']}   env_overrides: {json.dumps(r['env_overrides'])}",
                  f"started_utc: {r['started_utc']}   ended_utc: {r['ended_utc']}   duration_s: {r['duration_s']}",
                  f"exit_code: {r['exit_code']}   expected: {r['expect_exit']}   timed_out: {r['timed_out']}   "
                  f"timeout_s: {r['timeout_s']}"]
        if "wsl_script_exit_line" in r:
            lines.append(f"wsl_script_exit_line: {r['wsl_script_exit_line']}")
        lines += [f"stream: {st['kind']:<7} {st['sha256']}  {st['bytes']:>9} B  {st['file']}" for st in r["streams"]]
    (ctx.seat / "commands.txt").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    (ctx.seat / "commands.json").write_bytes(
        (json.dumps({"run": run, "steps": recs}, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode())
    # Census: this folder (except census + manifest) and both script-written bundles, repo-relative paths.
    rows = []
    for rel in sorted(p.relative_to(ctx.seat).as_posix() for p in ctx.seat.rglob("*")
                      if p.is_file() and p.name not in ("MANIFEST.sha256", "encoding-census.txt")):
        rows.append(census_row(ctx.seat / rel, f"proofs/windows/domain-matrix/{ctx.seat.name}/{rel}"))
    for brel in (ctx.win_bundle_rel, ctx.wsl_bundle_rel):
        broot = Path(ctx.clone) / brel
        for rel in sorted(p.relative_to(broot).as_posix() for p in broot.rglob("*") if p.is_file()):
            rows.append(census_row(broot / rel, f"{brel}/{rel}"))
    hdr = (f"{'path':<104} {'bytes':>8} {'utf8':>5} {'bom':>5} {'endings':>10} {'lf':>6} {'crlf':>6} {'cr':>3} "
           f"{'nonascii':>8} {'nul':>3} {'finalnl':>7}  sha256")
    cl = ["# Encoding census (UTF-8 validity, BOM, line endings): this folder plus both domain-matrix bundles",
          "# excludes this file and this folder's MANIFEST.sha256 (both UTF-8, no BOM, LF). Each bundle's own",
          "# MANIFEST.sha256 is listed as written by the smoke script.",
          "# lf = bare LF, crlf = CRLF pairs, cr = lone CR; endings = LF | CRLF | MIXED | no-newline | empty.", "", hdr]
    cl += [f"{r['path']:<104} {r['bytes']:>8} {str(r['utf8']):>5} {r['bom']:>5} {r['endings']:>10} {r['lf']:>6} "
           f"{r['crlf']:>6} {r['cr']:>3} {r['nonascii']:>8} {r['nul']:>3} {str(r['finalnl']):>7}  {r['sha256']}"
           for r in rows]
    (ctx.seat / "encoding-census.txt").write_bytes(("\n".join(cl) + "\n").encode("utf-8"))
    allf = sorted(p.relative_to(ctx.seat).as_posix() for p in ctx.seat.rglob("*")
                  if p.is_file() and p.name != "MANIFEST.sha256")
    (ctx.seat / "MANIFEST.sha256").write_bytes("".join(f"{sha256_file(ctx.seat / r)}  {r}\n" for r in allf).encode())
    print(f"rendered {len(allf)} files + MANIFEST.sha256 in {ctx.seat}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=("all", "render"))
    ap.add_argument("--stamp", required=True)
    a = ap.parse_args()
    ctx = Ctx(a.stamp)
    if a.mode == "render":
        cmd_render(ctx)
        return 0
    return cmd_all(ctx)


if __name__ == "__main__":
    sys.exit(main())
